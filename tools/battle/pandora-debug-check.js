#!/usr/bin/env node
'use strict';
const fs=require('fs');
const assert=require('assert');
const source=fs.readFileSync('monster-hero/src/game-system.jsx','utf8');
const data=source.slice(source.indexOf('const PANDORA_DEBUG'),source.indexOf('// 染色エンジンに3枠'));
assert(data.includes("baseHp:360, baseAtk:180, baseDef:100, baseGuts:135"));
assert(data.includes("plusStats:Object.freeze({hp:130,atk:35,def:25,guts:40})"));
assert(data.includes("distAptitude:Object.freeze(['B','B','B','B'])"));
assert(data.includes("baseMult:2.3,baseGuts:52"));
assert(data.includes("atkMotion:'pandoraDualThunder'"));
assert(!/ALL_PLAYER_MONSTERS\s*\.\s*Pandora|ALL_PLAYER_MONSTERS\s*\[\s*['\"]Pandora/.test(source),'正式モンスター登録しない');
assert(source.includes("mainHero?.id==='Pandora' && card.type==='unique' && card.monId!=='Pandora'"),'引継ぎ固有技だけ+50%');
assert(source.includes("mainHero?.id==='Pandora' && activeMon.id==='Pandora' && card.type==='unique' && card.monId==='Pandora') rollCombo(1.0+comboDmgBonus)"),'自身固有技は既存連撃へ100%を渡す');
assert(source.includes("mainHero?.id==='Pandora' && mon?.id==='Pandora' && card.type==='unique' && card.monId==='Pandora') total += extraHit(1.0+comboDmgBonus)"),'予測も同じ連撃式');
const combo=(base,bonus=0)=>base+Math.floor(base*(1+bonus));
assert.strictEqual(combo(1000),2000);
assert.strictEqual(combo(1000,.03),2030);
const inherited=(base,origin)=>Math.floor(base*(origin==='Pandora'?1:1.5));
assert.strictEqual(inherited(1000,'Zan'),1500);
assert.strictEqual(inherited(1000,'Pandora'),1000);
const cost=(base,{zero=false,resonance=0}={})=>{let value=zero?0:base;if(value>0&&resonance>0)value=Math.floor(value*.5);return value;};
assert.strictEqual(cost(52,{resonance:2}),26);
assert.strictEqual(cost(52,{zero:true,resonance:2}),0);
let turns=2;
assert.strictEqual(cost(52,{resonance:turns}),26); turns=Math.max(0,turns-1);
assert.strictEqual(cost(52,{resonance:turns}),26); turns=Math.max(0,turns-1);
assert.strictEqual(cost(52,{resonance:turns}),52);
turns=2; turns=2;
assert.strictEqual(cost(52,{resonance:turns}),26,'再発動しても25%にならない');
assert(source.includes("setNextTurnBuff('pandoraResonanceTurns',2)"));
assert(source.includes("if (resonanceRefresh==null && resonanceCarry>0)"));
assert(source.includes("animation:attackMotionAnimation(attackAnim)"));
assert(source.includes("animation:attackMotionAnimation({motion:p.atkMotion})"));
assert(source.includes('<MarketProductCard key={item.id} item={item} disabled canBuy={false}/>'));
console.log('OK: パンドラ候補データ・禁忌解錠・双極共振・共通モーション・DEBUGプレビュー');
