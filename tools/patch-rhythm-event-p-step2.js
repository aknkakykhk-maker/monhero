const fs=require('fs');
const path=require('path');
const file=path.join(__dirname,'mode','rhythm-event-window-check.js');
const src=fs.readFileSync(file,'utf8');
const old=`  const lines=topic.split('\\n').filter(line=>line.includes("{t:'"))\n    .filter(line=>line.includes('週間ランキング')||line.includes('対象曲'));`;
const next=`  const lines=topic.split('\\n').filter(line=>line.includes("{t:'"))\n    .filter(line=>line.includes('週間ランキング')||line.includes('対象曲'))\n    .filter(line=>!line.includes("releaseFlag:'rhythmEventPoints'"));`;
if(src.includes(next))process.exit(0);
if(!src.includes(old))throw new Error('rhythm-event-window-check.js の対象箇所が見つかりません');
fs.writeFileSync(file,src.replace(old,next));
console.log('イベントP専用ヘルプを週間ランキング公開フラグ検査から除外しました');
