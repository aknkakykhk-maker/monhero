#!/usr/bin/env node
const fs=require('fs');
const path=require('path');
const assert=require('assert');
const ROOT=path.resolve(__dirname,'..','..');
const candidate=JSON.parse(fs.readFileSync(path.join(ROOT,'monster-hero/debug/atsu-cup-theme-easy-formal-candidate-v1.json'),'utf8'));
const draft=JSON.parse(fs.readFileSync(path.join(ROOT,'tools/mode/authoring/atsu-cup-theme-easy-draft.json'),'utf8'));
const ui=fs.readFileSync(path.join(ROOT,'monster-hero/debug/rhythm-chart-authoring-ui.js'),'utf8');
const runtime=fs.readFileSync(path.join(ROOT,'monster-hero/data/rhythm-mode.js'),'utf8');
const calibration=fs.readFileSync(path.join(ROOT,'monster-hero/data/rhythm-geometry-calibration.js'),'utf8');
const ok=(name,value)=>{assert(value,name);console.log(`OK: ${name}`);};
const notes=Array.isArray(candidate.notes)?candidate.notes:[];
const review=Array.isArray(candidate.earReviewGrids)?candidate.earReviewGrids:[];
const sourceMap=new Map(draft.points.map(row=>[Number(row[0]),row]));
const selected=new Set(notes.map(note=>Number(note.grid)));
const expectedReview=draft.points.filter(row=>Math.abs(Number(row[2]))>30).map(row=>Number(row[0]));
ok('EASY正式候補v1は未完成レビュー状態',candidate.trackId==='atsu_cup_theme'&&candidate.difficulty==='EASY'&&candidate.candidateVersion===1&&candidate.status==='FORMAL_CANDIDATE'&&candidate.reviewRequired===true&&candidate.runtimeConnected===false);
ok('78ノーツ / TAP72 / HOLD6',candidate.noteCount===78&&notes.length===78&&candidate.typeCounts?.TAP===72&&candidate.typeCounts?.HOLD===6);
ok('耳確認22点は±30ms超と一致',review.length===22&&JSON.stringify(review)===JSON.stringify(expectedReview));
ok('正式候補は耳確認待ち22点をまだ採用しない',review.every(grid=>!selected.has(grid)));
ok('採用点はすべて元100候補由来',notes.every(note=>sourceMap.has(Number(note.grid))));
ok('採用点の音ピーク差は±30ms以内',notes.every(note=>Math.abs(Number(note.sourcePeakOffsetMs))<=30));
ok('採用点のstrength/offsetは元候補と一致',notes.every(note=>{const row=sourceMap.get(Number(note.grid));return Number(note.sourceStrength)===Number(row?.[1])&&Number(note.sourcePeakOffsetMs)===Number(row?.[2]);}));
ok('時系列・重複なし',notes.every((note,index)=>index===0||Number(note.grid)>Number(notes[index-1].grid)));
ok('EASY v1はTAP/HOLDだけ',notes.every(note=>note.type==='TAP'||note.type==='HOLD'));
ok('メイン5レーン中央・幅2だけを使用',notes.every(note=>Number.isInteger(note.lane)&&note.lane>=0&&note.lane<=4&&note.subLane===note.lane*2&&note.subLaneWidth===2));
const holds=notes.filter(note=>note.type==='HOLD');
ok('HOLDは4/8グリッドのみ',holds.length===6&&holds.every(note=>note.durationGrids===4||note.durationGrids===8));
ok('HOLD終端は次ノーツより前',holds.every(note=>{const index=notes.indexOf(note),next=notes[index+1];return !next||Number(note.grid)+Number(note.durationGrids)<Number(next.grid);}));
ok('エディタは正式候補v1を優先し旧100をfallback保持',ui.includes("FORMAL_CANDIDATE_URL='debug/atsu-cup-theme-easy-formal-candidate-v1.json'")&&ui.includes('loadFormalCandidate')&&ui.includes('if(!await loadFormalCandidate(false))await loadAutoDraft(false)')&&ui.includes('data-rhythm-chart-load-candidate'));
ok('正式候補のTAP/HOLDを既存draft形式へ変換',ui.includes('candidateNote=(row,trackId)=>')&&ui.includes("noteType==='HOLD'")&&ui.includes('durationGrids')&&ui.includes('note.endTimeMs=Math.round(endTimeMs)'));
ok('作者UIキャッシュを更新',calibration.includes("script.src='debug/rhythm-chart-authoring-ui.js?v=20260901d'"));
ok('正式runtimeへは未接続',!runtime.includes('atsu-cup-theme-easy-formal-candidate-v1'));
console.log('\nEASY正式候補v1チェック: OK');
