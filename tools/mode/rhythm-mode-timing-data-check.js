#!/usr/bin/env node
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const ROOT=path.resolve(__dirname,'..','..');
const source=fs.readFileSync(path.join(ROOT,'monster-hero/data/rhythm-timing.js'),'utf8');
let failed=0;
const check=(name,ok)=>{console.log(`${ok?'✓':'✗'} ${name}`);if(!ok)failed++;};
const ctx={Object,Number,Math};
vm.createContext(ctx);
vm.runInContext(`${source}\nthis.__timing=RHYTHM_TIMING_DATA.atsu_cup_theme;this.__at=rhythmTimingAt;this.__snap=rhythmSnapTimeToGrid;`,ctx);
const timing=ctx.__timing;
check('あつ杯テーマの制作タイミングデータがある',!!timing&&timing.trackId==='atsu_cup_theme');
check('実音源長144.64秒を保持',Math.abs(timing.audioDurationMs-144640)<=10);
check('制作基準BPMは169',timing.bpm===169);
check('1拍msが169BPMと一致',Math.abs(timing.beatMs-60000/169)<0.001);
check('解析由来オフセット40msを保持',timing.beatZeroMs===40&&timing.analysis.detectedBeatOffsetMs===40);
check('高解像度解析値169.014BPMを記録',Math.abs(timing.analysis.detectedBpm-169.014)<0.001);
check('実機タイミングは未確認として保持',timing.analysis.deviceTimingVerified===false);
const beat0=ctx.__at('atsu_cup_theme',0);
const beat1=ctx.__at('atsu_cup_theme',1);
const sixteenth=ctx.__at('atsu_cup_theme',0,1,4);
check('拍位置ヘルパーが単調に進む',beat0===40&&beat1>beat0&&sixteenth>beat0&&sixteenth<beat1);
const raw=sixteenth+17;
const snapped=ctx.__snap('atsu_cup_theme',raw,4);
check('任意時刻を16分グリッドへ吸着できる',Math.abs(snapped.timeMs-sixteenth)<0.001&&Math.abs(snapped.deltaMs-17)<0.001&&snapped.subdivisions===4);
check('未知トラックはnull',ctx.__at('missing',0)===null&&ctx.__snap('missing',1000)===null);
console.log(failed?`\n${failed}件のNGがあります`:'\nすべてOK');
process.exit(failed?1:0);
