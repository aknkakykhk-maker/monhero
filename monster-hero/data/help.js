// t:'data' は実データから作るので、ここでは中身を持たない(画面側で差し込む)
const helpBlockPlainText = (block) => {
  if (!block) return '';
  if (block.t === 'kv') return (block.rows || []).map(row => `${row[0]}: ${row[1]}`).join('\n');
  if (block.t === 'list' || block.t === 'steps') return (block.items || []).join('\n');
  if (block.t === 'note') return [block.title, block.text].filter(Boolean).join(': ');
  if (block.t === 'data') return '';
  return block.text || '';
};
