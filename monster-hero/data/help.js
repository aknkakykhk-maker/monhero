// ==================== ヘルプ(攻略情報局) ====================
// ヘルプの中身はJSXに直接書かず、ここでデータとして持つ。
//
// 【なぜデータにしているか】
// 今後「助手」がプレイヤーに説明する機能を入れる予定のため、画面表示と説明文を切り離しておく。
// 助手はここの assistant(ひとこと)と blocks(本文)をそのまま読み上げ・要約に使えるので、
// 画面を作り直しても説明文は1か所のままで済む。
// helpPlainText() でどのブロックからもプレーンテキストを取り出せる。
//
// 【構造】
//   HELP_CATEGORIES … カテゴリ(1画面目の大きなボタン)
//     └ topics       … トピック(2画面目の一覧。開くと本文が出る)
//         └ blocks   … 本文のかたまり
//
// 【blocks の種類】
//   { t:'p',     text }                       … 本文
//   { t:'note',  title?, text }               … 囲みの補足
//   { t:'list',  items:[ text, ... ] }        … 箇条書き
//   { t:'steps', items:[ text, ... ] }        … 番号つきの手順
//   { t:'kv',    rows:[ [左, 右], ... ] }      … 2列の表(内容を手で書く)
//   { t:'data',  id }                         … 2列の表(ゲームの実データから自動で作る)
//
// 【t:'data' について】
// 難易度の倍率・アイテムの値段・ログインボーナス・ミッションのように、
// ゲーム側のデータを変えたらヘルプも変わってほしいものは、手で書かずに t:'data' を使う。
// 実際の表は game-system.jsx の helpDataRows(id) が作るので、値の書き写し間違いや
// 「一部の難易度しか載っていない」といった取りこぼしが起きない。
// 使えるidは helpDataRows() を参照(difficulties / teachings / skipTickets / items /
// loginBonus / missionsDaily / missionsWeekly)。
//
// 【追加・修正するときの約束】★重要
//   ・機能を追加・変更したら、必ずこのファイルのヘルプも同時に更新する。
//     (画面を1つ増やしたら HELP_SCREEN_COVERAGE にも足す。足し忘れは
//      tools/help-coverage-check.js が失敗して教えてくれる)
//   ・トピックには必ず assistant(助手のひとこと)を1つ書く。助手が最初に話す一言になる。
//   ・数値を手で書くのは最後の手段。実データから作れるものは t:'data' にする
//     (手で書いた数値は tools/help-guide-check.js が実処理と照合する)。
//   ・id はヘルプ内のリンクや「前回見ていた場所」の保存に使うので、既存のものは変更しない。

// 助手の名前・画像・セリフは data/assistants.js が持つ。ここでは各項目の
// 「助手のひとこと(assistant)」だけを書く。

